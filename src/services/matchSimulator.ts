/**
 * Projects real pitch coordinates (x_m: [-52.5, 52.5], y_m: [-34.0, 34.0])
 * into realistic 2D broadcast camera perspective coordinates (1920x1080)
 * to demonstrate simulated computer-vision bounding boxes and pitch homography grid.
 */
export function pitchToBroadcastView(
  x_m: number,
  y_m: number,
  canvasW: number,
  canvasH: number
): { x: number; y: number; scale: number } {
  // Broadcast main stand perspective:
  // Far touchline is at y_m = -34m, near touchline is at y_m = +34m
  const normY = (y_m + 34.0) / 68.0; // 0 (far) to 1 (near)
  const normX = (x_m + 52.5) / 105.0; // 0 (left goal) to 1 (right goal)

  // Perspective compression: objects further away (normY near 0) are smaller and converge towards center
  const depthFactor = 0.55 + normY * 0.45; // 0.55 to 1.0

  // Perspective horizontal trapezoid spread
  const xSpan = 0.70 + normY * 0.28;
  const screenX = (0.5 + (normX - 0.5) * xSpan) * canvasW;
  const screenY = (0.24 + normY * 0.68) * canvasH;

  return { x: screenX, y: screenY, scale: depthFactor };
}
