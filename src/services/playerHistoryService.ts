// Search & Retrieval Functions
export function searchPlayerHistory(
  query: string,
  options?: {
    filterTeam?: "all" | "arsenal" | "mancity";
    filterRole?: string;
    onlyOpponentThreats?: boolean;
  }
): PlayerHistoricalProfile[] {
  const allProfiles = Object.values(HISTORICAL_PLAYERS_DB);
  const cleanQ = query.trim().toLowerCase();

  return allProfiles.filter((p) => {
    // Team filter
    if (options?.filterTeam && options.filterTeam !== "all") {
      if (options.filterTeam === "arsenal" && p.team !== "Arsenal") return false;
      if (options.filterTeam === "mancity" && p.team !== "Manchester City") return false;
    }

    // Role filter
    if (options?.filterRole && options.filterRole !== "all") {
      if (p.role !== options.filterRole) return false;
    }

    // Only opponent threats filter
    if (options?.onlyOpponentThreats && !p.isOpponent) {
      return false;
    }

    // If query is empty, return matching filter set
    if (!cleanQ) return true;

    // Search matching: name, full name, number, team, tags, position, vulnerabilities
    const matchesName = p.name.toLowerCase().includes(cleanQ) || p.fullName.toLowerCase().includes(cleanQ);
    const matchesNumber = p.shirtNumber.toString() === cleanQ;
    const matchesTeam = p.team.toLowerCase().includes(cleanQ);
    const matchesPosition = p.positionDetail.toLowerCase().includes(cleanQ) || p.role.toLowerCase() === cleanQ;
    const matchesTag = p.tags.some((t) => t.toLowerCase().includes(cleanQ));
    const matchesStrengths = p.strengths.some((s) => s.toLowerCase().includes(cleanQ));
    const matchesVulnerabilities = p.vulnerabilities.some(
      (v) => v.area.toLowerCase().includes(cleanQ) || v.description.toLowerCase().includes(cleanQ)
    );

    return (
      matchesName ||
      matchesNumber ||
      matchesTeam ||
      matchesPosition ||
      matchesTag ||
      matchesStrengths ||
      matchesVulnerabilities
    );
  });
}

// Get single profile by ID or match with live pitch player
export function getPlayerHistoricalProfile(id: number): PlayerHistoricalProfile | null {
  if (HISTORICAL_PLAYERS_DB[id]) {
    return HISTORICAL_PLAYERS_DB[id];
  }
  // Try finding by ID match or fallback
  const all = Object.values(HISTORICAL_PLAYERS_DB);
  const found = all.find((p) => p.id === id);
  return found || null;
}

// Map a live pitch player to a historical profile (matches name or shirt number or team)
export function mapLivePlayerToHistory(player: Player): PlayerHistoricalProfile | null {
  if (HISTORICAL_PLAYERS_DB[player.id]) {
    return HISTORICAL_PLAYERS_DB[player.id];
  }

  const all = Object.values(HISTORICAL_PLAYERS_DB);
  // Match by name or shirt number + team
  const byName = all.find(
    (p) =>
      p.name.toLowerCase() === player.name.toLowerCase() ||
      player.name.toLowerCase().includes(p.name.toLowerCase()) ||
      p.name.toLowerCase().includes(player.name.toLowerCase())
  );
  if (byName) return byName;

  const byNumber = all.find(
    (p) => p.shirtNumber === player.number && p.team.toLowerCase().includes(player.teamName.toLowerCase())
  );
  if (byNumber) return byNumber;

  return null;
}

// Return key opponent threats for instant coach one-click scouting
export function getOpponentKeyThreats(): PlayerHistoricalProfile[] {
  return Object.values(HISTORICAL_PLAYERS_DB)
    .filter((p) => p.isOpponent)
    .sort((a, b) => b.headToHead.historicalThreatScore - a.headToHead.historicalThreatScore);
}
